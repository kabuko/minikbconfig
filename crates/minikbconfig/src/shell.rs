//! Shell completion scripts, generated from the action grammar.
//!
//! Every word offered here comes from [`crate::complete`], which derives them
//! from the same tables the parser reads. Nothing is hand-listed, so the
//! completion cannot offer a spelling the grammar rejects.
//!
//! This is the one place where a mistake is paid for *before* the write rather
//! than after it, which is strictly better than any amount of read-back
//! checking.

use minikbconfig_core::keymap::KEY_SLOTS;

use minikbconfig_config::complete::words_with_modifiers;

/// The subcommands `minikbconfig` accepts.
///
/// Duplicated from the dispatch in `main.rs`, which a test checks. Offering a
/// command that does not exist is a small lie; omitting one that does is a
/// papercut nobody can report usefully.
pub const SUBCOMMANDS: [&str; 10] = [
    "info",
    "dump",
    "keys",
    "set",
    "led",
    "snapshot",
    "apply",
    "watch",
    "profile",
    "completions",
];

/// Every shell this can generate for.
pub const SHELLS: [&str; 3] = ["bash", "zsh", "fish"];

fn word_list() -> String {
    words_with_modifiers().join(" ")
}

fn slot_list() -> String {
    (0..KEY_SLOTS)
        .map(|i| i.to_string())
        .collect::<Vec<_>>()
        .join(" ")
}

fn subcommand_list() -> String {
    SUBCOMMANDS.join(" ")
}

/// A completion script for `shell`, or `None` if it is not one we generate for.
pub fn script_for(shell: &str) -> Option<String> {
    Some(match shell {
        "bash" => bash(),
        "zsh" => zsh(),
        "fish" => fish(),
        _ => return None,
    })
}

fn bash() -> String {
    format!(
        r#"# minikbconfig completion for bash.  Generated by `minikbconfig completions bash`.
_minikbconfig() {{
    local cur cmd i
    COMPREPLY=()
    cur="${{COMP_WORDS[COMP_CWORD]}}"

    # The subcommand is the first word after the program name that is not a
    # flag. Switching on this rather than on the previous word matters: for
    # `set 3 key:ctr` the previous word is the slot number, which says nothing
    # about what may follow.
    cmd=""
    for (( i = 1; i < COMP_CWORD; i++ )); do
        case "${{COMP_WORDS[i]}}" in
            -*) ;;
            *) cmd="${{COMP_WORDS[i]}}"; break ;;
        esac
    done

    case "$cmd" in
        set)
            if [[ "$cur" =~ ^- ]]; then
                COMPREPLY=( $(compgen -W "-V -l --layer" -- "$cur") )
            elif [[ "$cur" =~ ^[0-9]*$ ]]; then
                COMPREPLY=( $(compgen -W {slots} -- "$cur") )
            else
                COMPREPLY=( $(compgen -W {actions} -- "$cur") )
            fi
            ;;
        snapshot|apply)
            COMPREPLY=( $(compgen -f -- "$cur") ) ;;
        watch)
            COMPREPLY=( $(compgen -W "15 30 60 --raw" -- "$cur") ) ;;
        profile)
            COMPREPLY=( $(compgen -W "0 1 2 3 4 5" -- "$cur") ) ;;
        led)
            COMPREPLY=( $(compgen -W "on off key state 0 1 2 3 4 5 -b -m -c --speed --direction" -- "$cur") ) ;;
        completions)
            COMPREPLY=( $(compgen -W {shells} -- "$cur") ) ;;
        "")
            COMPREPLY=( $(compgen -W {subs} -- "$cur") ) ;;
    esac
    return 0
}}
complete -F _minikbconfig minikbconfig
"#,
        actions = shell_quote(&word_list()),
        slots = shell_quote(&slot_list()),
        subs = shell_quote(&subcommand_list()),
        shells = shell_quote(&SHELLS.join(" ")),
    )
}

fn zsh() -> String {
    format!(
        r#"#compdef minikbconfig
# minikbconfig completion for zsh.  Generated by `minikbconfig completions zsh`.
#
# Deliberately plain: find the subcommand, then offer a list. The `_arguments`
# state machine was tried first and its CURRENT indexing inside a `*::` state is
# relative, which is easy to get wrong and hard to notice.

_minikbconfig() {{
    local -a actions slots subs shells
    actions=({actions})
    slots=({slots})
    subs=({subs})
    shells=({shells})

    local cur="${{words[CURRENT]}}"

    if (( CURRENT == 1 )); then
        _describe -t commands 'minikbconfig command' subs && return 0
        return 1
    fi

    local cmd=""
    local i
    for (( i = 2; i < CURRENT; i++ )); do
        case "${{words[i]}}" in
            -*) ;;
            *) cmd="${{words[i]}}"; break ;;
        esac
    done

    case "$cmd" in
        set)
            if [[ "$cur" == -* ]]; then
                compadd -- -V -l --layer
            elif [[ "$cur" == <-> ]]; then
                compadd -a slots
            else
                compadd -a actions
            fi
            ;;
        snapshot|apply)
            _files && return 0 ;;
        watch)
            compadd -- 15 30 60 --raw ;;
        profile)
            compadd -- 0 1 2 3 4 5 ;;
        led)
            compadd -- on off key state 0 1 2 3 4 5 -b -m -c --speed --direction ;;
        completions)
            compadd -a shells ;;
        *)
            _describe -t commands 'minikbconfig command' subs && return 0 ;;
    esac
    return 0
}}

"#,
        actions = zsh_words(&words_with_modifiers()),
        slots = zsh_words(&(0..KEY_SLOTS).map(|i| i.to_string()).collect::<Vec<_>>()),
        subs = SUBCOMMANDS
            .iter()
            .map(|s| format!("'{s}'"))
            .collect::<Vec<_>>()
            .join(" "),
        shells = SHELLS
            .iter()
            .map(|s| format!("'{s}'"))
            .collect::<Vec<_>>()
            .join(" "),
    )
}

fn fish() -> String {
    let actions = words_with_modifiers();
    let slots: Vec<String> = (0..KEY_SLOTS).map(|i| i.to_string()).collect();
    let mut out = String::from(
        "# minikbconfig completion for fish.  Generated by `minikbconfig completions fish`.\n\n",
    );
    out.push_str(&format!(
        "complete -c minikbconfig -n '__fish_use_subcommand' -a '{}'\n",
        SUBCOMMANDS.join(" ")
    ));
    for action in &actions {
        // Fish treats spaces in a completion word literally, so escape them.
        out.push_str(&format!(
            "complete -c minikbconfig -n '__fish_seen_subcommand_from set' -a '{}\\n'\n",
            action.replace(' ', "\\ ")
        ));
    }
    out.push_str(&format!(
        "complete -c minikbconfig -n '__fish_seen_subcommand_from set' -a '{}'\n",
        slots.join(" ")
    ));
    out.push_str(
        "complete -c minikbconfig -n '__fish_seen_subcommand_from watch' -a '15 30 60 --raw'\n",
    );
    out.push_str(
        "complete -c minikbconfig -n '__fish_seen_subcommand_from profile' -a '0 1 2 3 4 5'\n\
         complete -c minikbconfig -n '__fish_seen_subcommand_from led' -a '0 1 2 3 4 5'\n",
    );
    out
}

fn shell_quote(words: &str) -> String {
    format!("\"{}\"", words.replace('"', "\\\""))
}

fn zsh_words(words: &[String]) -> String {
    words
        .iter()
        .map(|w| format!("'{}'", w.replace('\'', "'\\''")))
        .collect::<Vec<_>>()
        .join(" ")
}

/// Is this word something the user extends rather than something they finish?
///
/// Bare prefixes (`key:`, `move:`) and dangling modifiers (`key:ctrl-`) cannot
/// parse on their own — there is nothing yet for the parser to read after them.
/// They are still worth offering, because they are what a user types next.
#[cfg(test)]
fn is_prefix_word(word: &str) -> bool {
    word.ends_with(':') || word.ends_with('-')
}

#[cfg(test)]
mod tests {
    use super::*;
    use minikbconfig_config::action::{describe, parse_action};
    use minikbconfig_config::complete::full_words;

    #[test]
    fn every_offered_action_word_parses_or_is_a_prefix() {
        // The invariant that makes generated completion safe to install.
        for word in full_words() {
            assert!(
                parse_action(&word).is_ok() || is_prefix_word(&word),
                "offered word {word:?} can neither be used nor extended"
            );
        }
    }

    #[test]
    fn every_finished_word_renders_back_exactly() {
        // A word is "finished" when it is not a prefix. Prefixes have nothing to
        // round-trip, which is why `key:` and `key:ctrl-` are excluded by the
        // same rule rather than by a hand-picked list of exceptions.
        for word in full_words() {
            if is_prefix_word(&word) {
                continue;
            }
            let parsed = parse_action(&word).expect(&word);
            assert_eq!(describe(parsed), word);
        }
    }

    #[test]
    fn the_script_offers_every_whole_word() {
        for shell in SHELLS {
            let script = script_for(shell).unwrap_or_else(|| panic!("{shell}"));
            for word in full_words() {
                assert!(
                    script.contains(&word),
                    "{shell} completion is missing {word:?}"
                );
            }
        }
    }

    #[test]
    fn every_offered_word_either_parses_or_is_a_prefix() {
        for word in words_with_modifiers() {
            assert!(
                parse_action(&word).is_ok() || is_prefix_word(&word),
                "offered word {word:?} can neither be used nor extended"
            );
        }
    }

    #[test]
    fn every_script_names_every_subcommand() {
        for shell in SHELLS {
            let script = script_for(shell).expect(shell);
            for sub in SUBCOMMANDS {
                assert!(script.contains(sub), "{shell} completion is missing {sub}");
            }
        }
    }

    /// Read the dispatch out of `main.rs` at compile time and compare.
    ///
    /// Hand-maintained lists drift. This fails the build when a subcommand is
    /// added without updating completion, or spelled differently here.
    #[test]
    fn the_subcommand_list_matches_the_dispatch_table() {
        let source = include_str!("main.rs");
        let start = source
            .find("match command.as_str() {")
            .expect("dispatch match should exist");
        let block = &source[start..];
        let end = block
            .find("other =>")
            .expect("dispatch should fall through");

        let mut found: Vec<&str> = Vec::new();
        for line in block[..end].lines() {
            let line = line.trim_start();
            let Some(rest) = line.strip_prefix('"') else {
                continue;
            };
            let Some(close) = rest.find('"') else {
                continue;
            };
            if !rest[close..].contains("=>") {
                continue; // a string comparison, not an arm
            }
            found.push(&rest[..close]);
        }

        let mut expected = found.clone();
        expected.sort();
        let mut listed = SUBCOMMANDS.to_vec();
        listed.sort();
        assert_eq!(
            listed, expected,
            "SUBCOMMANDS is out of step with the dispatch table"
        );
    }

    #[test]
    fn an_unknown_shell_is_refused_rather_than_guessed() {
        assert!(script_for("powershell").is_none());
        assert!(script_for("nonsense").is_none());
    }

    #[test]
    fn quoting_survives_words_with_spaces() {
        // Actions contain no spaces today, but a key name could gain one, and a
        // broken script would be a nasty thing to debug from someone else's
        // shell.
        let quoted = shell_quote("a b \"c\"");
        assert_eq!(quoted, "\"a b \\\"c\\\"\"");
        let zsh = zsh_words(&["a'b".to_string()]);
        assert_eq!(zsh, "'a'\\''b'");
    }
}
